function buildUserInput(body) {
  const base = `
المرحلة: ${body.stageLabel || body.stage || "غير محدد"}
الاحتياج المختار: ${body.needLabel || body.need || "غير محدد"}
${body.otherNeed ? `الطلب الحر: ${body.otherNeed}` : ""}
التخصص: ${body.specialty || "غير محدد"}
الموضوع/الموقف: ${body.topic || "غير محدد"}
مستوى المتدربين: ${body.level || "غير محدد"}
عدد المتدربين: ${body.traineeCount || "غير محدد"}
الوقت المتاح: ${body.time || "غير محدد"}
النتيجة المطلوبة: ${body.goal || "غير محددة"}
معلومات/قيود إضافية: ${body.extra || "لا يوجد"}
`.trim();

  if (body.followUp) {
    return `${base}

هذا طلب متابعة على نفس الحل:
${body.followUp}

حافظ على سياق الحل السابق، وعدّل فقط ما يلزم. لا تبدأ من الصفر إلا إذا طلب المستخدم ذلك.`;
  }

  return `${base}

أنشئ الآن أفضل نتيجة عملية جاهزة لهذا المدرب. لا تعطِ قالبًا عامًا.`;
}

function buildContents(body) {
  const contents = [];

  if (Array.isArray(body.conversation)) {
    for (const m of body.conversation.slice(-6)) {
      if (!m || typeof m.content !== "string") continue;
      if (m.role !== "user" && m.role !== "assistant") continue;
      contents.push({
        role: m.role === "assistant" ? "model" : "user",
        parts: [{ text: m.content.slice(0, 12000) }]
      });
    }
  }

  contents.push({
    role: "user",
    parts: [{ text: buildUserInput(body) }]
  });

  return contents;
}

export default async function handler(req, res) {
  if (req.method !== "POST") {
    res.setHeader("Allow", "POST");
    return res.status(405).json({ error: "يُسمح بطلب POST فقط." });
  }

  if (!process.env.GEMINI_API_KEY) {
    return res.status(500).json({ error: "مفتاح Gemini API غير مضاف إلى إعدادات الخادم." });
  }

  try {
    const body = req.body || {};
    if (!body.topic || !body.stage || !body.need) {
      return res.status(400).json({ error: "البيانات الأساسية للطلب غير مكتملة." });
    }

    const response = await ai.models.generateContent({
      model: process.env.GEMINI_MODEL || "gemini-3.8-flash",
      contents: buildContents(body),
      config: {
        systemInstruction: SYSTEM_PROMPT,
        thinkingConfig: { thinkingLevel: "medium" },
        maxOutputTokens: 5000
      }
    });

    const answer = response.text?.trim();
    if (!answer) {
      return res.status(502).json({ error: "لم تصل استجابة نصية من النموذج. حاول مرة أخرى." });
    }

    return res.status(200).json({ answer });
  } catch (err) {
    console.error(err);
    const msg = String(err?.message || "");
    const status = Number(err?.status) || 500;

    const safeMessage =
      status === 429 || msg.includes("RESOURCE_EXHAUSTED")
        ? "يوجد ضغط أو تم الوصول إلى الحد المجاني مؤقتًا. انتظر قليلًا ثم حاول مرة أخرى."
        : status === 401 || status === 403
        ? "تعذر التحقق من مفتاح Gemini API أو صلاحيات المشروع."
        : "حدث خطأ أثناء توليد الاستجابة. حاول مرة أخرى.";

    return res.status(status >= 400 && status < 600 ? status : 500).json({ error: safeMessage });
  }
}
